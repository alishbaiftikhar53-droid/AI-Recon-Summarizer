import { useRef, useState, type KeyboardEvent } from 'react';
import { Send, Bot, User, TriangleAlert } from 'lucide-react';
import BackendRequirements from '@/components/assistant/BackendRequirements';
import Button from '@/components/ui/Button';
import Card from '@/components/ui/Card';
import { DemoBadge } from '@/components/ui/Badges';
import { askAssistant, getApiBaseUrl } from '@/lib/backendApi';
import { errorMessage } from '@/lib/format';

interface Message {
  id: number;
  role: 'user' | 'assistant' | 'error';
  text: string;
}

const SUGGESTIONS = [
  'Which findings should be addressed first?',
  'Which exposed services need the closest review?',
  'What should be verified before this scan is reported?',
];

interface AssistantPanelProps {
  scanId: string;
  scanName: string;
  isDemo: boolean;
}

export default function AssistantPanel({ scanId, scanName, isDemo }: AssistantPanelProps) {
  const baseUrl = getApiBaseUrl();
  const [messages, setMessages] = useState<Message[]>([]);
  const [draft, setDraft] = useState('');
  const [pending, setPending] = useState(false);
  const nextId = useRef(1);

  if (!baseUrl) return <BackendRequirements />;

  async function send(question: string) {
    const text = question.trim();
    if (!text || pending) return;
    const userMessage: Message = { id: nextId.current++, role: 'user', text };
    setMessages((current) => [...current, userMessage]);
    setDraft('');
    setPending(true);
    try {
      const { answer } = await askAssistant(baseUrl, scanId, text);
      setMessages((current) => [...current, { id: nextId.current++, role: 'assistant', text: answer }]);
    } catch (err) {
      setMessages((current) => [...current, { id: nextId.current++, role: 'error', text: errorMessage(err) }]);
    } finally {
      setPending(false);
    }
  }

  function handleKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault();
      void send(draft);
    }
  }

  return (
    <Card
      title="Security assistant"
      description="Ask questions about this scan. Answers are generated by your connected AI backend, not by this app."
      action={isDemo ? <DemoBadge /> : undefined}
    >
      <div className="flex min-h-80 flex-col gap-4">
        <div className="max-h-[480px] flex-1 space-y-4 overflow-y-auto rounded-xl border border-night-700/70 bg-night-900/60 p-4">
          {messages.length === 0 && (
            <div className="space-y-4 py-6 text-center">
              <p className="text-sm text-night-300">Ask a question about “{scanName}”.</p>
              <div className="flex flex-wrap justify-center gap-2">
                {SUGGESTIONS.map((suggestion) => (
                  <button
                    key={suggestion}
                    type="button"
                    onClick={() => void send(suggestion)}
                    disabled={pending}
                    className="rounded-full border border-night-600 bg-night-800 px-3 py-1.5 text-xs text-night-200 transition duration-200 hover:border-electric-500/60 hover:text-electric-200 disabled:opacity-50"
                  >
                    {suggestion}
                  </button>
                ))}
              </div>
            </div>
          )}

          {messages.map((message) => {
            const isUser = message.role === 'user';
            const isError = message.role === 'error';
            return (
              <div key={message.id} className={`flex gap-3 animate-fade-in ${isUser ? 'justify-end' : ''}`}>
                {!isUser && (
                  <div
                    className={`mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg ${
                      isError ? 'bg-red-500/15 text-red-300' : 'bg-electric-500/15 text-electric-300'
                    }`}
                  >
                    {isError ? <TriangleAlert className="h-4 w-4" aria-hidden /> : <Bot className="h-4 w-4" aria-hidden />}
                  </div>
                )}
                <div
                  className={`max-w-[85%] whitespace-pre-line rounded-2xl px-4 py-3 text-sm leading-relaxed ${
                    isUser
                      ? 'bg-electric-600 text-white'
                      : isError
                        ? 'border border-red-500/40 bg-red-500/10 text-red-100'
                        : 'border border-night-700 bg-night-850 text-night-100'
                  }`}
                >
                  {message.text}
                </div>
                {isUser && (
                  <div className="mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-night-700 text-night-200">
                    <User className="h-4 w-4" aria-hidden />
                  </div>
                )}
              </div>
            );
          })}

          {pending && <p className="text-xs text-night-400">Waiting for the backend to respond...</p>}
        </div>

        <div className="flex items-end gap-3">
          <textarea
            className="field min-h-11 resize-none"
            rows={2}
            placeholder="Ask about ports, services or findings"
            value={draft}
            maxLength={2000}
            onChange={(event) => setDraft(event.target.value)}
            onKeyDown={handleKeyDown}
            aria-label="Question for the security assistant"
          />
          <Button variant="primary" onClick={() => void send(draft)} disabled={!draft.trim()} loading={pending}>
            <Send className="h-4 w-4" aria-hidden />
            Send
          </Button>
        </div>
        <p className="text-xs text-night-400">
          AI answers can be wrong or incomplete. Check them against the scan results before acting on them.
        </p>
      </div>
    </Card>
  );
}
